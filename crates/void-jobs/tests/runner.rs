#[test]
fn t49_cancel_running_kill_and_late_result_quarantined() {
    let f = fixture();
    let r = runner(&f);
    let token = r.cancel_token();
    let s = spec(serde_json::json!({"mode":"sleep","durationMs":100}));
    f.db.submit(&s).unwrap();
    let jid = s.job_id.clone();
    let s_run = s.clone();
    // Runner moves into the worker thread (JobDb conn is !Sync); the
    // test cancels via the token + a second connection — exactly how a
    // CancelJob op would reach it.
    let handle = std::thread::spawn(move || {
        let c = ctx_static();
        r.run(&s_run, &c)
    });
    std::thread::sleep(Duration::from_millis(200));
    let db2 = JobDb::open(f.root.path().join("index.db")).unwrap();
    db2.cancel(&jid).unwrap(); // running → cancelling
    token.cancel(); // runner-side cooperative cancel
    let out = handle.join().unwrap().unwrap();
    assert!(matches!(out, RunOutcome::Cancelled { .. }), "{out:?}");
    let rec = f.db.get(&jid).unwrap();
    assert_eq!(rec.status, JobStatus::Cancelled);
    // No provenance/result publish; staging torn down.
    assert!(!f
        .root
        .path()
        .join("jobs")
        .join(&jid)
        .join("provenance.json")
        .exists());
    assert!(!f
        .root
        .path()
        .join("staging")
        .join(format!("job-{jid}"))
        .exists());
}

fn ctx_static() -> RunContext<'static> {
    // Tests spawn against the module-level built binary — the path is
    // leaked once, keeping the borrow static for the worker thread.
    static RUNTIME: std::sync::OnceLock<WorkerRuntime> = std::sync::OnceLock::new();
    RunContext {
        runtime: RUNTIME.get_or_init(|| WorkerRuntime::new(worker_exe())),
        budget: generous(),
        model_version: Some("1.0.0".into()),
    }
}

