//! W12 runner boundary tests (TEST_MATRIX T49–T52) — every job runs the
//! REAL `void-fake-worker` binary (workers/fake), built from this test's
//! setup. Artifacts are genuine synth output: a fresh sine WAV per spec.

use std::fs;
use std::path::{Path, PathBuf};

use std::time::Duration;
use void_assets::AssetStore;
use void_jobs::{
    decide, Admit, JobBudget, JobDb, JobKind, JobRunner, JobSpec, JobStatus, Reservations,
    RunContext, RunOutcome, WorkerRuntime,
};

fn worker_exe() -> PathBuf {
    // Build the real fixture binary once per test-process run; a
    // missing or stale binary fails loudly rather than passing mocked.
    //
    // `cargo build` re-emits the destination binary (unlink+hardlink)
    // even on a fresh check — observed on macOS as intermittent
    // ENOENT/“binary missing” when 13 parallel tests each invoked the
    // same build. `OnceLock` serializes it so every spawn happens after
    // the single replacement completes.
    static EXE: std::sync::OnceLock<PathBuf> = std::sync::OnceLock::new();
    EXE.get_or_init(|| {
        let root = PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("../..");
        let manifest = root.join("workers/fake/Cargo.toml");
        let status = std::process::Command::new(env!("CARGO"))
            .args(["build", "--manifest-path"])
            .arg(&manifest)
            .status()
            .expect("cargo build fake worker");
        assert!(status.success(), "fake worker build failed");
        let exe = root.join("workers/fake/target/debug/void-fake-worker");
        assert!(exe.is_file(), "fake worker binary missing at {exe:?}");
        exe
    })
    .clone()
}

fn spec(params: serde_json::Value) -> JobSpec {
    JobSpec {
        job_id: uuid::Uuid::new_v4().to_string(),
        project_id: uuid::Uuid::new_v4().to_string(),
        source_revision: "7".into(),
        context_sha256: "ab".repeat(32),
        kind: JobKind::Symbolic,
        runtime_id: "void-fake-worker".into(),
        runtime_sha256: "cd".repeat(32),
        model_id: Some("fake-synth".into()),
        model_sha256: Some("ef".repeat(32)),
        inputs: vec!["11".repeat(32)],
        parameters: params,
        reservations: Reservations {
            ram_bytes: (64 * 1024 * 1024u64).to_string(),
            vram_bytes: "0".into(),
            cpu_threads: 1,
        },
        deadline_monotonic_ns: "0".into(),
        output_scope_token: "test-scope".into(),
        cloud_consent_id: None,
    }
}

struct Fixture {
    root: tempfile::TempDir,
    db: JobDb,
    store: AssetStore,
    runtime: WorkerRuntime,
}

fn fixture() -> Fixture {
    let root = tempfile::tempdir().unwrap();
    let db = JobDb::open(root.path().join("index.db")).unwrap();
    let store = AssetStore::new(root.path().join("assets"), 64 * 1024 * 1024).unwrap();
    let runtime = WorkerRuntime::new(worker_exe());
    Fixture {
        root,
        db,
        store,
        runtime,
    }
}

fn runner(f: &Fixture) -> JobRunner {
    // JobRunner takes the db by value — open a second connection over
    // the same file (schema owner remains the first).
    let db = JobDb::open(f.root.path().join("index.db")).unwrap();
    JobRunner::new(db, f.store.clone(), f.root.path().to_path_buf())
}

fn budget(cpu_seconds: u64, memory_bytes: u64, wall_ns: u64) -> JobBudget {
    JobBudget {
        cpu_seconds,
        memory_bytes,
        vram_bytes: 0,
        deadline_monotonic_ns: 0,
        wall_ns,
    }
}

fn ctx<'a>(runtime: &'a WorkerRuntime, b: JobBudget) -> RunContext<'a> {
    RunContext {
        runtime,
        budget: b,
        model_version: Some("1.0.0".into()),
    }
}

fn generous() -> JobBudget {
    budget(60, 256 * 1024 * 1024, 30_000_000_000)
}

fn wav_sha(path: &Path) -> String {
    let b = fs::read(path).unwrap();
    use sha2::{Digest, Sha256};
    let mut h = Sha256::new();
    h.update(&b);
    h.finalize().iter().map(|x| format!("{x:02x}")).collect()
}

#[test]
fn t49_happy_path_real_sine_wav_and_provenance() {
    let f = fixture();
    let r = runner(&f);
    let s = spec(serde_json::json!({"mode":"succeed","durationMs":50,"freqHz":330,"seed":7}));
    f.db.submit(&s).unwrap();
    let jid = s.job_id.clone();
    let out = r.run(&s, &ctx(&f.runtime, generous())).unwrap();
    let RunOutcome::Succeeded {
        artifacts,
        stray_files,
        ..
    } = out
    else {
        panic!("expected success: {out:?}")
    };
    assert_eq!(stray_files, 0);
    assert_eq!(artifacts.len(), 1);
    // Real generated bytes: the WAV in the store hashes to the
    // provenance-recorded sha and starts with RIFF.
    let abs = &artifacts[0].asset_abs;
    assert!(abs.is_file());
    assert_eq!(&fs::read(abs).unwrap()[..4], b"RIFF");
    assert_eq!(artifacts[0].sha256, wav_sha(abs));
    assert_eq!(f.db.get(&jid).unwrap().status, JobStatus::Succeeded);
    // provenance.json + result.json published beside the asset refs.
    let dir = f.root.path().join("jobs").join(&jid);
    let prov: serde_json::Value =
        serde_json::from_slice(&fs::read(dir.join("provenance.json")).unwrap()).unwrap();
    assert_eq!(prov["jobId"], jid);
    assert_eq!(prov["modelId"], "fake-synth");
    assert_eq!(prov["modelVersion"], "1.0.0");
    assert_eq!(prov["sourceRevision"], "7");
    assert_eq!(prov["artifacts"][0]["sha256"], artifacts[0].sha256);
    assert_eq!(prov["parameters"]["freqHz"], 330);
    assert!(prov["runtime"]["argvSha256"].as_str().unwrap().len() == 64);
    assert_eq!(prov["runtime"]["executable"], "void-fake-worker");
    assert_eq!(prov["inputs"][0], "11".repeat(32));
    let card: serde_json::Value =
        serde_json::from_slice(&fs::read(dir.join("result.json")).unwrap()).unwrap();
    assert_eq!(card["status"], "succeeded");
}

