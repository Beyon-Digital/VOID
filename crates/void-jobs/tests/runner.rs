#[test]
fn t50_admission_four_waiting_one_heavy_two_small() {
    let f = fixture();
    let light = serde_json::json!({"mode":"succeed"});
    let mk = |ram: &str, vram: &str, threads: u32| {
        let mut s = spec(light.clone());
        s.reservations = Reservations {
            ram_bytes: ram.into(),
            vram_bytes: vram.into(),
            cpu_threads: threads,
        };
        s
    };
    // Two small running + one heavy running → both slots taken.
    let small1 = mk("67108864", "0", 1);
    let small2 = mk("67108864", "0", 1);
    let heavy = mk("34359738368", "0", 8);
    for s in [&small1, &small2, &heavy] {
        f.db.submit(s).unwrap();
        f.db.start(&s.job_id).unwrap();
    }
    // A third small job: running slots exhausted → Queue.
    assert_eq!(
        decide(&f.db, &mk("67108864", "0", 1)).unwrap(),
        Admit::Queue
    );
    // A second heavy: heavy slot taken → Queue.
    assert_eq!(
        decide(&f.db, &mk("34359738368", "0", 8)).unwrap(),
        Admit::Queue
    );
    // Fill the waiting room: 4 queued.
    for _ in 0..4 {
        let s = mk("67108864", "0", 1);
        f.db.submit(&s).unwrap();
    }
    // Fifth waiter is refused.
    match decide(&f.db, &mk("67108864", "0", 1)) {
        Err(e) => assert!(e.to_string().contains("full"), "{e}"),
        a => panic!("expected Busy, got {a:?}"),
    }
    // Fresh db: no contention → StartNow.
    let f2 = fixture();
    assert_eq!(
        decide(&f2.db, &mk("67108864", "0", 1)).unwrap(),
        Admit::StartNow
    );
}

#[test]
fn t49_stray_files_counted_not_committed() {
    let f = fixture();
    let r = runner(&f);
    let s = spec(serde_json::json!({"mode":"stray","durationMs":20}));
    f.db.submit(&s).unwrap();
    let out = r.run(&s, &ctx(&f.runtime, generous())).unwrap();
    match out {
        RunOutcome::Succeeded {
            artifacts,
            stray_files,
            ..
        } => {
            assert_eq!(artifacts.len(), 1);
            assert_eq!(stray_files, 1, "stray.bin counted, never imported");
        }
        o => panic!("{o:?}"),
    }
    let prov: serde_json::Value = serde_json::from_slice(
        &fs::read(
            f.root
                .path()
                .join("jobs")
                .join(&s.job_id)
                .join("provenance.json"),
        )
        .unwrap(),
    )
    .unwrap();
    assert_eq!(prov["measured"]["strayFiles"], 1);
    // Store contains exactly the declared artifact.
    let mut count = 0;
    for e in fs::read_dir(f.root.path().join("assets/sha256")).unwrap() {
        e.unwrap();
        count += 1;
    }
    assert_eq!(count, 1);
}

